"""Builds bosses.js from SchaleDB raids.min.json + enemies.min.json.
Run: python -I gen_boss.py research/raids.json research/enemies.json
Only game data goes in here: no cast timings exist in SchaleDB (see research/bosses-*.md)."""
import json, re, sys

raids = json.load(open(sys.argv[1], encoding='utf8'))
enemies = json.load(open(sys.argv[2], encoding='utf8'))
DIFF = ['Normal', 'Hard', 'VeryHard', 'Hardcore', 'Extreme', 'Insane', 'Torment', 'Lunatic']
STAT = {'ATK': 'ATK', 'DEF': 'DEF', 'HIT': 'Accuracy', 'MAXHP': 'Max HP', 'CostRegen': 'Cost Recovery', 'CostChange': 'EX cost', 'AttackSpeed': 'Attack Speed',
        'MoveSpeed': 'Move Speed', 'CriticalChance': 'Crit Rate', 'CriticalDamage': 'Crit Damage', 'CriticalDamageRateResist': 'Crit Damage Resist',
        'CriticalChanceResistPoint': 'Crit Rate Resist', 'DamageRatio': 'Damage Dealt', 'DamagedRatio': 'Damage Taken', 'HealEffectiveness': 'Healing Received',
        'HealPower': 'Healing', 'HealedLimit': 'Healing Received', 'EnhanceExDamageRate': 'EX Damage', 'ReduceExDamagedRate': 'EX Damage Taken',
        'EnhanceExplosionRate': 'Explosive Damage', 'EnhancePierceRate': 'Piercing Damage', 'EnhanceMysticRate': 'Mystic Damage', 'EnhanceSonicRate': 'Sonic Damage',
        'ConcentratedTarget': 'Focus Target', 'Stability': 'Stability', 'Penetration': 'Penetration', 'Shield': 'Shield', 'Dodge': 'Evasion',
        'ElectricShock': 'Shock', 'CostRegenBan': 'Cost Recovery Lock', 'SuddenDeath': 'Sudden Death', 'FormChange': 'Form Change'}
def stat_label(m):
    name, lab = m.group(2), m.group(3)
    if lab: return lab
    return STAT.get(name) or re.sub(r'(?<=[a-z])(?=[A-Z])', ' ', name)
def clean_tags(s):
    return re.sub(r"<([bdcs]):([A-Za-z0-9_]+)(?:='([^']*)')?>", stat_label, s)
clean = lambda s: re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', clean_tags((s or '').replace('<br>', ' '))).replace('\n', ' ')).strip()
SK = raids['RaidSkills']
ESK = enemies['Skills']

def enemy(eid):
    e = enemies['Enemies'].get(str(eid))
    if not e:
        return None
    return {'id': eid, 'name': e['Name'], 'rank': e.get('Rank'), 'hp': e.get('MaxHP100'), 'armor': e.get('ArmorType'), 'bullet': e.get('BulletType'),
            'groggyGauge': e.get('GroggyGauge'), 'groggyMs': e.get('GroggyTime'),
            'phases': [p['Argument'] for p in (e.get('PhaseChange') or []) if p.get('Trigger') == 'HPUnder']}

def effects_of(sid, desc):
    """Cost-recovery buffs that the boss gives the players when it goes groggy (Binah Lunatic)."""
    out = []
    es = ESK.get(sid) or {}
    for ef in es.get('Effects', []):
        if ef.get('Type') == 'Buff' and ef.get('Stat') == 'RegenCost_Base' and re.search(r'(becomes|goes|is) groggy', desc, re.I):
            val = ef['Value'][0][0]
            m = re.search(r'for (\d+(?:\.\d+)?)s', desc)
            out.append({'on': 'groggy', 'stat': 'RegenCost', 'value': val, 'who': 'Main' if re.search(r'Striker', desc) else 'All',
                        'sec': float(m.group(1)) if m else None})
    return out

# Grand Assault: the same bosses, but the player picks the boss's armor type per season; for each armor the highest difficulty any season opened.
ga = {}
for se in raids['RaidSeasons'][0]['EliminateSeasons']:
    g = ga.setdefault(se['RaidId'], {'armors': {}, 'seasons': 0})
    g['seasons'] += 1
    for armor, mx in se['OpenDifficulty'].items():
        g['armors'][armor] = max(g['armors'].get(armor, 0), mx)
bosses = []
for r in raids['Raid']:
    jp_max = r['MaxDifficulty'][0]
    diffs = []
    for k in range(min(len(r['EnemyList']), jp_max + 1)):
        ids = r['EnemyList'][k]
        es = [x for x in (enemy(i) for i in ids) if x]
        if not es:
            continue
        skills = []
        for sid in r['RaidSkillList'][k]:
            s = SK.get(sid)
            if not s:
                continue
            desc = clean(s.get('Desc'))
            sk = {'id': sid, 'name': s.get('Name'), 'type': s.get('SkillType'), 'desc': desc}
            fx = effects_of(sid, desc)
            if fx:
                sk['fx'] = fx
            skills.append(sk)
        diffs.append({'k': k, 'name': DIFF[k] if k < len(DIFF) else str(k), 'sec': r['BattleDuration'][k], 'enemies': es, 'skills': skills})
    bosses.append({'id': r['Id'], 'path': r['PathName'], 'name': r['Name'], 'terrains': r['Terrain'], 'armor': r['ArmorType'],
                   'bullet': r['BulletType'], 'bulletInsane': r.get('BulletTypeInsane'), 'jp': r['IsReleased'][0], 'global': r['IsReleased'][1], 'ga': ga.get(r['Id']), 'diffs': diffs})

open('bosses.js', 'w', encoding='utf8').write('// Generated by gen_boss.py from SchaleDB raid data. Skill TIMINGS are not in the data.\nconst BOSSES = ' + json.dumps(bosses, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(len(bosses), 'bosses,', sum(len(b['diffs']) for b in bosses), 'difficulties')
